#!/usr/bin/env python3
"""Generate committed local SVG assets/catalog from the original icon source of truth."""
import json
from pathlib import Path
from html import escape
ROOT = Path(__file__).resolve().parents[1]
icons = json.loads((ROOT / '_data/icons.json').read_text())
attrs = 'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"'
out = ROOT / 'assets/icons'
out.mkdir(exist_ok=True)
symbols = []
for name, icon in icons.items():
    body = f'<path d="{icon["path"]}"/>'
    (out / f'{name}.svg').write_text(f'<svg xmlns="http://www.w3.org/2000/svg" {attrs} role="img" aria-label="{escape(icon["title"])}">{body}</svg>\n')
    symbols.append(f'<symbol id="{name}" {attrs}>{body}</symbol>')
(out / 'sprite.svg').write_text('<svg xmlns="http://www.w3.org/2000/svg">' + ''.join(symbols) + '</svg>\n')
# Only fixed local icon names are accepted; no user-controlled SVG markup.
js = '/* Generated by _scripts/build-icons.py; edit _data/icons.json instead. */\n'
js += '(function () { "use strict"; const paths = ' + json.dumps({k:v['path'] for k,v in icons.items()}) + ';\n'
js += '''globalThis.SiteIcons = { render: function (name, className) {
 if (!Object.prototype.hasOwnProperty.call(paths, name)) return '';
 const safeClass = String(className || '').replace(/[^a-zA-Z0-9 _-]/g, '');
 return '<svg class="site-icon ' + safeClass + '" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"><path d="' + paths[name] + '"/></svg>';
}};
})();
'''
(ROOT / 'assets/js/icons.js').write_text(js)
# Catalog stays a developer asset, not a new public top-level navigation destination.
cards = ''.join(f'<div class="card"><svg {attrs} width="24" height="24" aria-hidden="true"><path d="{v["path"]}"/></svg><div>{escape(k)}<small>{escape(v["title"])}</small></div><svg {attrs} width="16" height="16" aria-hidden="true"><path d="{v["path"]}"/></svg></div>' for k,v in icons.items())
html = '''<!doctype html><html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>YangCazz · 原创图标目录</title><style>
*{box-sizing:border-box}body{margin:0;font:14px/1.5 system-ui,sans-serif;background:#f5f6f8;color:#243048}main{max-width:1260px;margin:auto;padding:32px}h1{font-size:25px;margin:0}p{color:#627086}.grid{display:grid;grid-template-columns:repeat(4,minmax(0,1fr));gap:12px}.card{display:flex;align-items:center;gap:14px;padding:16px;background:#fff;border:1px solid #dce2eb;border-radius:10px}.card>div{min-width:0;overflow-wrap:anywhere}.card>svg{flex-shrink:0}.card>svg:last-child{margin-left:auto;opacity:.8}small{display:block;font-size:11px;color:#627086}.dark{background:#111a2a;color:#e7edf7;padding:28px;border-radius:16px;margin-top:28px}.dark .card{background:#1a273b;border-color:#35445e}.dark small{color:#a8b5cb}.dark h2{margin-top:0}@media(max-width:700px){.grid{grid-template-columns:repeat(2,minmax(0,1fr))}main{padding:20px}.dark{padding:16px}.card{padding:10px;gap:8px;font-size:11px}}
</style><main><h1>YangCazz · Outline / 24</h1><p>原创矢量图标 · 24 px 网格 · 1.75 px 圆角描边 · 左 24 px / 右 16 px · currentColor</p><section class="grid">'''+cards+'''</section><section class="dark"><h2>暗色对照 / Dark reference</h2><div class="grid">'''+cards+'''</div></section></main></html>'''
(out / 'catalog.html').write_text(html)
print(f'Generated {len(icons)} icons, sprite, runtime and catalog.')
# Each icon remains discoverable even before first UI use (catalog is a real consumer).
import hashlib
sources = [*ROOT.glob('*.html'), *ROOT.glob('_includes/*.html'), *ROOT.glob('_layouts/*.html'),
           *ROOT.glob('assets/js/*.js'), *ROOT.glob('apps/**/*.html'), *ROOT.glob('apps/**/*.js'),
           *ROOT.glob('_sass/*.scss'), ROOT / '_data/navigation.yml']
manifest = []
for name, icon in icons.items():
    uses = ['assets/icons/catalog.html']
    for source in sources:
        if source.name == 'icons.js':
            continue
        text = source.read_text()
        if any(token in text for token in (f'name="{name}"', f"render('{name}'", f'sprite.svg#{name}"', f'icons/{name}.svg', f'icon: {name}\n')):
            uses.append(str(source.relative_to(ROOT)))
    path = f'/assets/icons/{name}.svg'
    manifest.append({
        'id': f'outline24-{name}', 'path': path, 'kind': 'original-icon', 'title': icon['title'],
        'alt': icon['title'], 'source_url': None, 'source_title': '_data/icons.json / original coordinate drawing',
        'source_date': '2026-10-30', 'verified_at': '2026-10-30',
        'rights': '为本站原创绘制；不是第三方商标、Octicons 临摹或产品照片',
        'used_by': sorted(set(uses)), 'grid': '24x24', 'stroke_width': 1.75,
        'provenance': 'assistant-authored native SVG paths; no raster generation model',
        'sha256': hashlib.sha256((ROOT / path.lstrip('/')).read_bytes()).hexdigest()
    })
(ROOT / '_data/visual_assets/icons-20261030.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
# Brand identifiers are retained from existing repository artwork, not redrawn or claimed as original.
brands = json.loads((ROOT / '_data/brand_icons.json').read_text())
(out / 'brands').mkdir(exist_ok=True)
for name, brand in brands.items():
    path = f'/assets/icons/brands/{name}.svg'
    (ROOT / path.lstrip('/')).write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="currentColor" role="img" aria-label="{brand["title"]}"><path d="{brand["path"]}"/></svg>\n')
    uses = [str(p.relative_to(ROOT)) for p in sources if f'brand-icon.html name="{name}"' in p.read_text()]
    manifest.append({'id': f'brand-{name}', 'path': path, 'kind': 'brand-mark', 'title': brand['title'], 'alt': brand['title'],
        'source_url': 'https://github.com/YangCazz/YangCazz.github.io/blob/71090bd7020861829a82873a1b8170e35b22d791/_layouts/default.html',
        'source_title': 'Existing footer inline SVG; centralized without altering path', 'verified_at': '2026-10-30',
        'rights': '既有品牌识别图形；商标属于各权利人，非本站原创，不宣称获得官方背书。仅沿用原仓库用途。',
        'used_by': uses, 'sha256': hashlib.sha256((ROOT / path.lstrip('/')).read_bytes()).hexdigest()})
(ROOT / '_data/visual_assets/icons-20261030.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
